-- 目标：MySQL 8.4 / utf8mb4；订单日期为 2026-01-01 至 2026-10-14，不依赖 NOW()。
-- 首次导入使用。重复导入遇到主键冲突时应停止并回滚；本脚本不删除任何已有库表。
-- 8 张表：50 客户、6 分类、24 商品、120 订单、300 明细、110 收退款流水、60 评价、17 字典项。
-- 金额单位：人民币元。subtotal_amount 为折后明细小计；total_amount = subtotal - 订单优惠 + 运费。
-- 成交口径：订单状态 20/30/40；净实收口径：成功收款减成功退款，使用 payments 事件日期。
-- 一对多 JOIN 请先按订单聚合，避免订单金额随订单明细或支付事件重复累计。
SET NAMES utf8mb4;
SET time_zone = '+08:00';
CREATE DATABASE IF NOT EXISTS deepseek_demo CHARACTER SET utf8mb4 COLLATE utf8mb4_0900_ai_ci;
USE deepseek_demo;

CREATE TABLE IF NOT EXISTS sys_dict_data (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '字典项编号',
  dict_type VARCHAR(40) NOT NULL COMMENT '对应业务字段名，供工作台自动解析枚举',
  dict_value VARCHAR(40) NOT NULL COMMENT '存储值',
  dict_label VARCHAR(80) NOT NULL COMMENT '中文含义',
  UNIQUE KEY uk_dict_type_value (dict_type, dict_value)
) ENGINE=InnoDB COMMENT='业务字典；用于测试工作台自动识别状态与类型';

CREATE TABLE IF NOT EXISTS customers (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '客户内部编号',
  customer_no VARCHAR(16) NOT NULL COMMENT '客户业务编号',
  name VARCHAR(80) NOT NULL COMMENT '合成客户名称',
  city VARCHAR(30) NOT NULL COMMENT '客户所在城市',
  email VARCHAR(100) NULL COMMENT '合成邮箱，example.test 为测试域名；部分为空',
  member_level TINYINT UNSIGNED NOT NULL COMMENT '会员等级：0=普通会员,1=银卡会员,2=金卡会员',
  is_active TINYINT UNSIGNED NOT NULL DEFAULT 1 COMMENT '账号状态：0=停用,1=正常',
  registered_at DATETIME NOT NULL COMMENT '注册时间，固定北京时间',
  UNIQUE KEY uk_customer_no (customer_no),
  KEY idx_customer_city (city),
  KEY idx_customer_registered (registered_at)
) ENGINE=InnoDB COMMENT='合成客户资料；编号 41 至 50 从未下单';

CREATE TABLE IF NOT EXISTS categories (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '分类编号',
  name VARCHAR(50) NOT NULL COMMENT '分类中文名称',
  sort_order INT UNSIGNED NOT NULL COMMENT '展示顺序'
) ENGINE=InnoDB COMMENT='商品分类；每类四种商品';

CREATE TABLE IF NOT EXISTS products (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '商品编号',
  sku VARCHAR(30) NOT NULL COMMENT '库存编码',
  category_id INT UNSIGNED NOT NULL COMMENT '所属分类',
  name VARCHAR(100) NOT NULL COMMENT '商品名称',
  price DECIMAL(12,2) NOT NULL COMMENT '当前商品单价，人民币元；历史订单以明细单价为准',
  stock INT UNSIGNED NOT NULL COMMENT '当前可售库存；部分商品售罄',
  is_active TINYINT UNSIGNED NOT NULL COMMENT '上架状态：0=下架,1=上架',
  attributes JSON NULL COMMENT '演示品牌和产地',
  listed_at DATETIME NOT NULL COMMENT '首次上架时间',
  UNIQUE KEY uk_product_sku (sku),
  KEY idx_product_category (category_id),
  CONSTRAINT fk_product_category FOREIGN KEY (category_id) REFERENCES categories (id)
) ENGINE=InnoDB COMMENT='商品目录与库存；已下架商品仍可能有历史订单';

CREATE TABLE IF NOT EXISTS orders (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '订单编号',
  order_no VARCHAR(30) NOT NULL COMMENT '订单业务流水号',
  customer_id INT UNSIGNED NOT NULL COMMENT '下单客户',
  order_status TINYINT UNSIGNED NOT NULL COMMENT '状态：10=待支付,20=已支付,30=已发货,40=已完成,50=已取消,60=已退款',
  channel ENUM('web','mobile','miniapp') NOT NULL COMMENT '订单来源渠道，含义见字典 channel',
  subtotal_amount DECIMAL(12,2) NOT NULL COMMENT '所有明细 line_amount 合计，已扣明细优惠',
  discount_amount DECIMAL(12,2) NOT NULL COMMENT '整单优惠金额，不含明细优惠',
  shipping_fee DECIMAL(12,2) NOT NULL COMMENT '运费',
  total_amount DECIMAL(12,2) NOT NULL COMMENT '应付金额=小计-整单优惠+运费；待付和取消订单不代表实际收入',
  created_at DATETIME NOT NULL COMMENT '下单时间，北京时间',
  paid_at DATETIME NULL COMMENT '首次成功支付时间；待支付和取消订单为空',
  shipped_at DATETIME NULL COMMENT '发货时间',
  completed_at DATETIME NULL COMMENT '完成时间；退款订单为退款前已完成时间',
  cancelled_at DATETIME NULL COMMENT '取消时间，仅取消订单有值',
  UNIQUE KEY uk_order_no (order_no),
  KEY idx_order_customer (customer_id),
  KEY idx_order_created_status (created_at, order_status),
  KEY idx_order_paid (paid_at),
  CONSTRAINT fk_order_customer FOREIGN KEY (customer_id) REFERENCES customers (id)
) ENGINE=InnoDB COMMENT='120 张订单，涵盖六种状态与十个月份；退款订单均全额退款';

CREATE TABLE IF NOT EXISTS order_items (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '明细编号',
  order_id INT UNSIGNED NOT NULL COMMENT '所属订单',
  product_id INT UNSIGNED NOT NULL COMMENT '购买商品',
  quantity INT UNSIGNED NOT NULL COMMENT '购买件数',
  unit_price DECIMAL(12,2) NOT NULL COMMENT '下单时商品单价，人民币元',
  discount_amount DECIMAL(12,2) NOT NULL COMMENT '该行全部商品的优惠金额',
  line_amount DECIMAL(12,2) NOT NULL COMMENT '明细实价=单价*件数-明细优惠，尚未分摊整单优惠及运费',
  KEY idx_item_order (order_id),
  KEY idx_item_product (product_id),
  CONSTRAINT fk_item_order FOREIGN KEY (order_id) REFERENCES orders (id),
  CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products (id)
) ENGINE=InnoDB COMMENT='300 条订单商品明细；所有状态订单均保留明细';

CREATE TABLE IF NOT EXISTS payments (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '资金事件编号',
  order_id INT UNSIGNED NOT NULL COMMENT '所属订单',
  transaction_no VARCHAR(30) NOT NULL COMMENT '合成收款或退款流水号',
  event_type ENUM('payment','refund') NOT NULL COMMENT 'payment=成功收款,refund=成功退款；退款金额以正数存储',
  method ENUM('alipay','wechat','bank_card') NOT NULL COMMENT '支付方式，含义见字典 method',
  status ENUM('success','failed','pending') NOT NULL COMMENT '资金事件状态，本数据集所有事件均为 success',
  amount DECIMAL(12,2) NOT NULL COMMENT '事件金额，人民币元，始终为正数；计算净收入时退款应扣减',
  occurred_at DATETIME NOT NULL COMMENT '资金事件发生时间，北京时间',
  UNIQUE KEY uk_payment_transaction (transaction_no),
  KEY idx_payment_order (order_id),
  KEY idx_payment_occurred (occurred_at),
  CONSTRAINT fk_payment_order FOREIGN KEY (order_id) REFERENCES orders (id)
) ENGINE=InnoDB COMMENT='100 条成功收款及 10 条全额退款；同一退款订单有两个资金事件';

CREATE TABLE IF NOT EXISTS product_reviews (
  id INT UNSIGNED NOT NULL PRIMARY KEY COMMENT '评价编号',
  order_item_id INT UNSIGNED NOT NULL COMMENT '被评价的购买明细；每条明细至多一条评价',
  customer_id INT UNSIGNED NOT NULL COMMENT '评价客户，与订单客户一致',
  product_id INT UNSIGNED NOT NULL COMMENT '被评价商品，与购买明细一致',
  rating TINYINT UNSIGNED NOT NULL COMMENT '评分：1 至 5 分，5 为最佳',
  content VARCHAR(300) NOT NULL COMMENT '合成中文评价',
  merchant_reply VARCHAR(200) NULL COMMENT '商家回复；部分为空',
  created_at DATETIME NOT NULL COMMENT '评价时间，为订单下单后四天',
  UNIQUE KEY uk_review_item (order_item_id),
  KEY idx_review_product_rating (product_id, rating),
  KEY idx_review_customer (customer_id),
  CONSTRAINT fk_review_item FOREIGN KEY (order_item_id) REFERENCES order_items (id),
  CONSTRAINT fk_review_customer FOREIGN KEY (customer_id) REFERENCES customers (id),
  CONSTRAINT fk_review_product FOREIGN KEY (product_id) REFERENCES products (id),
  CONSTRAINT chk_review_rating CHECK (rating BETWEEN 1 AND 5)
) ENGINE=InnoDB COMMENT='60 条已完成订单的合成购买评价，适合商品口碑与销量联合分析';

